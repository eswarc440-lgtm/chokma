export function findCatalogCourseForSkill(skillName: string): CatalogCourse {
  const lower = skillName.toLowerCase();
  const exact = OFFICIAL_COURSE_CATALOG.find(
    (c) => c.targetSkill.toLowerCase() === lower || c.title.toLowerCase().includes(lower)
  );
  if (exact) return exact;
  return {
    id: `cat_custom_${lower.replace(/[^a-z0-9]/g, '_')}`,
    title: `${skillName} Foundations & Practical Labs`,
    provider: 'Official Documentation',
    officialUrl: `https://www.google.com/search?q=${encodeURIComponent(skillName + ' official documentation tutorial')}`,
    targetSkill: skillName,
    difficulty: 'Beginner',
    durationLabel: '4h 00m',
    pricingType: 'Free',
    summary: `Structured core fundamentals and hands-on exercises for ${skillName}.`,
    youtubeVideoId: 'SOTamWNgDKc',
    videoChannel: 'freeCodeCamp.org',
    lessons: [
      `Core Architecture & Mental Model of ${skillName}`,
      `Hands-On Configuration & Key Workflows in ${skillName}`,
      `Common Failure Modes & Diagnostics for ${skillName}`,
      `Production Best Practices & Interview Readiness`,
    ],
  };
}
